Purpose
In order to ensure consistent staffing levels to support patient access, timely call handling, and quality service we need our employees to be reliable in their attendance. Missing work, or even reporting late to work not only limits patient access, but also puts a strain on everyone else in the department.

The information contained in this policy will serve to add boundaries for attendance and install a mechanism to fairly assess points. This policy is not intended to establish a contract of employment; the employment relationship between you and WWFP remains employment at will.

Regular attendance is considered an essential function of every position and, as such, all employees are expected to be in their assigned area ready to begin their assigned tasks at the start of their shift. It is acceptable for employees to clock in up to 10 minutes prior to shift start. The area lead or department manager will need to approve any start times earlier than 10 minutes ahead of the shift start time listed on your schedule in Paycor.

All employees are expected to:
- Be logged in and ready to take calls at the start of their scheduled shift
- Adhere to assigned schedules, including breaks and lunches
- Notify their supervisor of absences or tardiness as early as possible

Point System
- Tardy (3 minutes late - 2 hours late): 0.25 points
- 2+ hours of shift missed (in late or out early): 0.50 points
- Early departure (leaving 10+ minutes before shift ends): 0.25 points
- Late call-in (after 7 am): 0.25 points
- Unscheduled absence (call-in) with PTO available: 1 point
- Unscheduled absence (call-in) without PTO available: 2 points
- No call / no show**: 4 points
**If employment is not terminated per policy due to extenuating circumstances.

Notes:
- Tardiness includes not being logged into phone systems on time.
- If PTO balance falls below amount needed for approved absence, points will apply according to amount of time PTO is not available. For example, employee was scheduled to work 8 hours. PTO available balance is 5 hours, the 3 hours of time that the employee misses will result in 0.50 points.
- PTO will be used if available.
- Consecutive missed days count as one occurrence if properly reported (as described below in the call-off procedure) and a doctor''s note is provided requiring the employee to be off of work each day of the absence. If the illness is for a family member the same requirement applies. Consecutive day absences not excused by a doctor will be charged either 1 point (with PTO available) or 2 points (no PTO available) per day missed.

Call-Off Procedure
- Employees must notify their supervisor or follow department protocol at least 1-2 hours prior to shift start.
- If the notification is not received by 7 am, 0.25 points will be assessed for the late call in. These points will be assessed in addition to the points received for the call-in.
- Notification should include reason and expected return date.

Point Thresholds & Corrective Action
- 4 points: Verbal warning
- 6 points: Written warning
- 8 points: Final warning
- 10 points: Termination of employment

Point Reduction / Reset
- Points roll off after 6 months from the date of occurrence.
- Employees with no occurrences for 90 consecutive days may have 1 point removed.

Exceptions (No Points Applied)
- Approved PTO (scheduled at least 24 hours in advance) with available PTO to cover absence.
- FMLA or approved medical leave.
- Work comp leave arising from injury or illness occurring at WWFP.
- Jury duty, bereavement/funeral leave, or other approved paid leaves.
- Pre-approved schedule changes.
- Released from work due to overstaffing.
- Off of work due to an incident of domestic violence or sexual assault (applicable to the victim only).

Call Center-Specific Expectations
- Repeated tardiness impacting call queue coverage may result in additional coaching.
- Excessive schedule adherence issues (break/lunch overages) may be managed under performance, separate from attendance points.
- High call volume periods may require stricter adherence.

Employees in Orientation Period
Employees who accumulate 4 points within their first 90 days of employment may be terminated due to excessive absenteeism. Points will not be applied to any absences relayed to lead or manager during the first week of employment.

Manager Discretion
Supervisors may consider extenuating circumstances and adjust points when appropriate, in alignment with company policies.

